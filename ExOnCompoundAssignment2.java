public class ExOnCompoundAssignment2 {
    public static void main(String[] args) {

        int salary = 25000;
        salary += 5000;
        System.out.println(salary);

        int marks = 90;
        marks -= 20;
        System.out.println(marks);

        int number = 15;
        number *= 3;
        System.out.println(number);

        int price = 1000;
        price /= 4;
        System.out.println(price);

        int remainder = 25;
        remainder %= 4;
        System.out.println(remainder);
    }
}
