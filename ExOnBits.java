public class ExOnBits {
    public static void main(String[] args) {
        System.out.println(25 | 30); // bitwise OR
        System.out.println(25 & 30); // bitwise AND
        System.out.println(25 ^ 30); // bitwise XOR
        System.out.println(25 & 30); // bitwise AND
        System.out.println(25 << 30); // left shift
        System.out.println(25 >> 30); // right shift
        System.out.println(25 ^ 30); // bitwise XOR
        System.out.println(~5); // bitwise NOT
        System.out.println("yes"); // ternary operator
        System.out.println(5); // ternary operator with numbers
        System.out.println("greater"); // ternary operator with strings
        System.out.println(5); // ternary operator with numbers
    }
}