public class ExOnBits {
    public static void main(String[] args) {
        System.out.println(25 | 30);
        System.out.println(25 & 30);
        System.out.println(25 ^ 30);
        System.out.println(25 & 30);
        System.out.println(25 << 30);
        System.out.println(25 >> 30);
        System.out.println(25 ^ 30);
        System.out.println(~5);
    }
}