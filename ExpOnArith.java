
public class ExpOnArith {

    public static void main(String[] args) {

        // Addition
        System.out.println("10 + 20 = " + (10 + 20));

        // Subtraction
        System.out.println("10 - 20 = " + (10 - 20));

        // Multiplication
        System.out.println("10 * 20 = " + (10 * 20));

        // Division
        System.out.println("10 / 20 = " + (10.0 / 20));

        // Modulus (Remainder)
        System.out.println("10 % 20 = " + (10 % 20));
    }
}
