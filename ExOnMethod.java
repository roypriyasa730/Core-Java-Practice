public class ExOnMethod {
    public static void add() {
        int a = 10;
        int b = 20;
        System.out.println(a + b);
    }

    public static void sub() {
        int a = 100;
        int b = 20;
        System.out.println(a - b);
    }

    public static void mul() {
        int a = 100;
        int b = 20;
        System.out.println(a * b);
    }

    public static void mod() {
        int a = 100;
        int b = 20;
        System.out.println(a % b);
    }

    public static void div() {
        int a = 100;
        int b = 20;
        System.out.println(a / b);
    }

    public static void main(String[] args) {
        add();
        sub();
        mul();
        mod();
        div();

    }

}
