public class ExOnCondition {
    public static void main(String[] args) {
        int num = 5;
        if (num < 0) {
            System.out.println("it is +ve");

        } else if (num < 0) {
            System.out.println("it is -ve");
            System.out.println("End of program");
        } else if (num == 0) {
            System.out.println("it is zero");
            System.out.println("End of program");
        }
        System.out.println("End of program");

    }
}